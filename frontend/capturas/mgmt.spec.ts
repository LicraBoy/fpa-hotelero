import { expect, test } from '@playwright/test'
import { mkdirSync } from 'node:fs'
import { resolve } from 'node:path'

// Mgmt & Check In con datos reales: importa el Excel del Budget a la COPIA de la base y captura la
// Hoja de sección, el Editor mensual y la Comparación anual (docs/imagenes/mgmt/).
const SALIDA = resolve('../docs/imagenes/mgmt')
const EXCEL = resolve('../docs/-1% - MZT Budget 26-27 TC 18.00 Final.xlsx')
mkdirSync(SALIDA, { recursive: true })

test('mgmt: importar, hoja, editor y comparación', async ({ page }) => {
  await page.setViewportSize({ width: 1536, height: 1024 })
  await page.goto('/')
  await page.getByLabel('Usuario (desarrollo)').selectOption({ label: 'Contralor' })
  await page.getByRole('navigation', { name: 'Secciones' }).getByRole('button', { name: 'Budget Studio' }).click()
  await page.getByRole('tab', { name: 'Captura' }).click()
  await page.getByRole('region', { name: 'Captura de Budget' }).waitFor({ timeout: 30_000 })
  await page.getByRole('button', { name: 'Abrir la hoja de Mgmt & Check In' }).click()
  await page.getByRole('region', { name: 'Hoja de cuentas por mes' }).waitFor()
  await page.getByLabel('Excel del Budget con la hoja Mgmt & Check In').setInputFiles(EXCEL)
  await expect(page.getByText(/Se importaron \d+ cuentas desde el Excel/)).toBeVisible({ timeout: 60_000 })
  await page.waitForTimeout(800)
  await page.screenshot({ path: `${SALIDA}/1-hoja.png`, fullPage: true })
  await page.getByRole('tab', { name: 'Comparación anual' }).click()
  await page.getByRole('img', { name: 'Comparativo anual' }).waitFor()
  await page.waitForTimeout(500)
  await page.screenshot({ path: `${SALIDA}/3-comparacion.png`, fullPage: true })
  await page.getByRole('button', { name: 'Volver a la Hoja de sección' }).click()
  // Una cuenta con partidas: su Hoja de cuenta, la comparación y el editor de una partida
  await page.locator('.fila-linea-boton', { hasText: 'Other Fringe' }).first().click()
  await page.getByRole('region', { name: 'Hoja de cuentas por mes' }).waitFor()
  await page.waitForTimeout(800)
  await page.screenshot({ path: `${SALIDA}/4-hoja-de-cuenta-other-fringe.png`, fullPage: true })
  await page.getByRole('tab', { name: 'Comparación anual' }).click()
  await page.getByRole('img', { name: 'Comparativo anual' }).waitFor()
  await page.waitForTimeout(500)
  await page.screenshot({ path: `${SALIDA}/5-comparacion-other-fringe.png`, fullPage: true })
  await page.getByRole('button', { name: 'Volver a la Hoja de cuenta' }).click()
  await page.locator('.fila-linea-boton', { hasText: 'COMPANY PICNIC' }).first().click()
  await page.getByRole('region', { name: 'Meses de la partida' }).waitFor()
  await page.waitForTimeout(500)
  await page.screenshot({ path: `${SALIDA}/6-editor-de-partida.png`, fullPage: true })
  await page.getByRole('button', { name: 'Volver a la Hoja de cuenta' }).click()
  await page.getByRole('button', { name: 'Volver a la Hoja de sección' }).click()
  // Insurance no tiene hoja de detalle: se captura con el Editor mensual (Telephone ya va por partidas)
  await page.locator('.fila-linea-boton', { hasText: 'Insurance' }).first().click()
  await page.getByRole('region', { name: 'Meses de la cuenta' }).waitFor()
  await page.waitForTimeout(500)
  await page.screenshot({ path: `${SALIDA}/2-editor-insurance.png`, fullPage: true })
})
